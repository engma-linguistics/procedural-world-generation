def orth_of(l: dict) -> R.Orthography:
    """The lect's spelling (romanize.Orthography): its phonemes, its allophones spelled as their phonemes, its book folds
    ranked by token counts in its lexicon (the same plan names.py and output.py use)."""
    k = id(l)
    if k in _ORTH and _ORTH[k][0] is l:
        return _ORTH[k][1]
    inv = l.get("inventory") or {}
    allo = {}
    for a in inv.get("allophones") or []:
        if not isinstance(a, dict):
            continue  # (an old or fake file lists bare symbols: nothing to map)
        x = seg(a.get("ipa", ""))
        if x is not None:
            allo[x] = (seg(a["of"]) if a.get("of") else None, a.get("test"))
    counts: dict = {}
    for e in (l.get("lexicon") or {}).values():
        for s in R.from_ipa(e.get("ipa") or ""):
            counts[s] = counts.get(s, 0) + 1
    segs = set(inv_segments(l)) | set(counts)
    o = R.Orthography(segs, allo, counts)
    _ORTH[k] = (l, o)
    return o


def rule_text(doc: Doc, rid: str) -> str:
    t = doc.rules.get(rid, rid)
    return re.sub(r"\s*\([a-z]+:[^)]*\)\s*$", "", t)


def word_cell(entry: dict | None) -> tuple[str, str]:
    if not entry:
        return "–", "–"
    return entry.get("ipa", "–"), entry.get("roman", "–")


# ---- etymology in short ---------------------------------------------------------------------------------------------------

def etym_short(doc: Doc, entry: dict, lid: str, max_steps: int = 4) -> str:
    ch = doc.chain(entry.get("etym"))
    if not ch:
        return ""
    gloss = None
    parts = []
    for n in ch:
        proc, form = n[3], n[4]
        g = n[5] if len(n) > 5 and n[5] else gloss
        note = n[6] if len(n) > 6 else ""
        when = f"{n[1]:g}" if n[1] is not None else "?"
        if proc == "proto":
            parts.append(f"\\*{form} '{g}' ({doc.label(n[2], True)}, {when} kyr)")
        elif proc == "coin":
            parts.append(f"coined {form} '{g}' ({when})")
        elif proc.startswith("borrow:"):
            parts.append(f"borrowed from {doc.label(proc.split(':', 1)[1], True)} ({when})")
        elif proc.startswith("substrate"):
            parts.append(f"kept from the substrate ({when})")
        elif proc.startswith("compound:"):
            parts.append(f"{proc.split(':', 1)[1].replace('+', ' + ')} = '{g}' ({when})")
        elif proc.startswith("derive:"):
            base = note.split(" + ")[0] if note else "?"
            parts.append(f"{base} + '{proc.split(':', 1)[1]}' = '{g}' ({when})")
        elif proc.startswith("shift:"):
            parts.append(f"'{gloss}' > '{g}' ({when})")
        elif proc == "taboo":
            parts.append(f"taboo replacement ({when})")
        elif proc.startswith("sound_change") or proc in ("nativize", "analogy"):
            pass
        else:
            parts.append(f"{proc} ({when})")
        gloss = g
    if len(parts) > max_steps:
        parts = parts[:1] + ["…"] + parts[-(max_steps - 1):]
    return " → ".join(parts)


def etym_origin(doc: Doc, entry: dict) -> str:
    """inherited | coined | borrowed | substrate: the word's first non-sound-change event."""
    ch = doc.chain(entry.get("etym"))
    kinds = [n[3].split(":")[0] for n in ch if not n[3].startswith("sound_change")]
    if any(k == "borrow" for k in kinds):
        return "borrowed"
    if kinds and kinds[0] == "proto":
        return "inherited" if all(k == "proto" for k in kinds) else "inherited, remade"
    return "coined"


