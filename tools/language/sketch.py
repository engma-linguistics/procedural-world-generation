def _and(xs: list[str]) -> str:
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def typology_prose(t: dict) -> list[str]:
    def g(k, d="?"):
        return t.get(k, d)
    out = []
    wo = g("word_order")
    order = "free (no basic order of subject, object and verb)" if wo == "free" else f"{wo}"
    adp = {"pre": "prepositions", "post": "postpositions", "mixed": "both prepositions and postpositions",
           "none": "no adpositions"}.get(g("adposition"), g("adposition"))
    s = f"Basic word order is {order}; it has {adp}."
    np = []
    for k, a, b in (("genitive", "possessor before the possessed", "possessed before the possessor"),
                    ("adjective", "adjective before the noun", "noun before the adjective"),
                    ("demonstrative", "demonstrative before the noun", "noun before the demonstrative"),
                    ("numeral", "numeral before the noun", "noun before the numeral"),
                    ("relative", "relative clause before the noun", "noun before the relative clause")):
        v = g(k)
        first = {"genitive": "GN", "adjective": "AN", "demonstrative": "DemN", "numeral": "NumN", "relative": "RelN"}[k]
        if v == first:
            np.append(a)
        elif v in ("mixed", "other"):
            np.append(f"{k} order varies")
        elif v != "?":
            np.append(b)
    if np:
        s += " In the noun phrase: " + "; ".join(np) + "."
    hd = g("head_direction")
    if hd != "?":
        s += f" Overall it is head-{hd}."
    out.append(s)

    art = []
    da, ia = g("definite_article"), g("indefinite_article")
    if da == "none":
        art.append("no definite article")
    elif da != "?":
        art.append(f"a definite article {'before' if da == 'pre' else 'after'} the noun")
    art.append("an indefinite article" if ia == "present" else "no indefinite article")
    case = {"none": "no case marking on nouns", "few": "a few cases", "many": "a rich case system"}.get(g("case"), "")
    al = {"neutral": "no alignment marking (subject and object are not told apart by form)",
          "nom-acc": "nominative-accusative alignment", "erg-abs": "ergative-absolutive alignment",
          "split": "split alignment (ergative in some contexts, accusative in others)"}.get(g("alignment"), "")
    num = {"none": "no grammatical number", "sg-pl": "singular and plural", "sg-du-pl": "singular, dual and plural"
           }.get(g("number"), "")
    gen = {"none": "no gender or noun classes", "sex": "a gender system based on sex",
           "animacy": "gender by animacy", "classes": "a system of noun classes"}.get(g("gender"), "")
    out.append("It has " + ", ".join(x for x in art + [case, al, num, gen] if x) + ".")

    tam = [k for k in ("past", "future", "perfective", "progressive", "habitual") if g(k) == "marked"]
    ev = {"none": "are no evidentials", "indirect": "is an indirect (reported or inferred) evidential",
          "direct+indirect": "are both direct and indirect evidentials"}.get(g("evidentiality"), "")
    s = "Verbs mark " + (_and(tam) if tam else "no tense or aspect category") + (f"; there {ev}." if ev else ".")
    neg = {"preverbal": "a negator before the verb", "postverbal": "a negator after the verb",
           "clause_initial": "a clause-initial negator", "clause_final": "a clause-final negator"}.get(g("negation"))
    q = {"final_particle": "a final question particle", "initial_particle": "an initial question particle",
         "intonation": "intonation alone", "verb_morph": "a verb form"}.get(g("polar_question"))
    if neg:
        s += f" Negation uses {neg}; yes/no questions use {q}."
    agr = g("verb_agreement")
    if agr not in ("?", "none"):
        s += f" Verbs agree with the subject by {'prefixes and suffixes' if agr == 'both' else agr + 'es'}"
        oa = g("object_agreement")
        s += (f" and with the object by {oa}es." if oa not in ("none", "?") else "; not with the object.")
    elif agr == "none":
        s += " Verbs do not agree with their arguments."
    out.append(s)

    flags = []
    for k, yes in (("pro_drop", "pronouns can be dropped"), ("clusivity", "an inclusive/exclusive 'we' distinction"),
                   ("alienability", "alienable and inalienable possession told apart"),
                   ("numeral_classifiers", "numeral classifiers"), ("serial_verbs", "serial verbs"),
                   ("verb_reduplication", "verb reduplication"), ("copula", "a copula"),
                   ("adjective_verb_like", "adjectives that behave like verbs")):
        if g(k) == "yes":
            flags.append(yes)
    other = []
    if g("causative") != "?":
        other.append(f"a {g('causative')} causative")
    if g("passive") not in ("?", "none"):
        other.append(f"a {g('passive')} passive")
    elif g("passive") == "none":
        other.append("no passive")
    if g("wh_in_situ") == "yes":
        other.append("question words left in place")
    elif g("wh_in_situ") == "no":
        other.append("question words moved to the front")
    if g("numeral_base") not in ("?", "other"):
        other.append(f"a {g('numeral_base')} counting base")
    poss = {"have": "a 'have' verb for possession", "locational": "locational possession ('at me is a dog')"}.get(
        g("predicative_possession"))
    if poss:
        other.append(poss)
    if flags or other:
        out.append("Other features: " + "; ".join(flags + other) + ".")
    return out


