# ---- English-likeness -----------------------------------------------------------------------------------------------------

_ENG_C = [seg(x) for x in ENGLISH_CONSONANTS]
_ENG_V = [seg(x) for x in ENGLISH_VOWELS]


def chamfer(a: list, b: list) -> float:
    """Mean of (each a's distance to its nearest b) and (each b's to its nearest a), over percept distance (tone
    and length ignored: tone is scored separately)."""
    if not a or not b:
        return 10.0

    a = [replace(x, tone=0) for x in a]
    b = [replace(x, tone=0) for x in b]
    ab = statistics.mean(min(P.distance(x, y) for y in b) for x in a)
    ba = statistics.mean(min(P.distance(x, y) for y in a) for x in b)
    return (ab + ba) / 2


def english_score(l: dict) -> tuple[float, dict]:
    inv = l.get("inventory") or {}
    t = l.get("typology") or {}
    cs = [s for s in (seg(x) for x in inv.get("consonants", [])) if s]
    vs = [s for s in (seg(x) for x in inv.get("vowels", [])) if s]
    comp = {}
    comp["consonants"] = 1 / (1 + chamfer(_ENG_C, cs))
    comp["vowels"] = 1 / (1 + chamfer(_ENG_V, vs))
    on, co = inv.get("max_onset", 1), inv.get("max_coda", 0)
    closed = sum(v for k, v in (inv.get("shapes") or {}).items() if k.endswith("C"))
    comp["syllables"] = 0.6 * (1 - (abs(ENGLISH_MAX_ONSET - on) + abs(ENGLISH_MAX_CODA - co)) / 7) + 0.4 * min(1, closed / 0.6)
    comp["no_tone"] = 0.0 if inv.get("tones") else 1.0
    comp["stress"] = {"initial": 1.0, "penult": 0.75, "final": 0.5}.get(inv.get("stress"), 0.0)
    syl = (l.get("stats") or {}).get("core_mean_syllables", 2.5)
    comp["word_length"] = max(0.0, 1 - abs(syl - ENGLISH_CORE_SYLLABLES) / 2)
    comp["svo"] = {"SVO": 1.0, "free": 0.25}.get(t.get("word_order"), 0.0)
    comp["prepositions"] = {"pre": 1.0, "mixed": 0.5}.get(t.get("adposition"), 0.0)
    comp["articles"] = (2 / 3) * {"pre": 1.0, "post": 0.5}.get(t.get("definite_article"), 0.0) + \
        (1 / 3) * (t.get("indefinite_article") == "present")
    comp["little_case"] = {"none": 1.0, "few": 0.75}.get(t.get("case"), 0.0)
    grams = l.get("grams") or []
    comp["analytic"] = (sum((g.get("level") or 0) <= 1 for g in grams) / len(grams)) if grams else 1.0
    comp["typology"] = sum(t.get(k) in v for k, v in ENGLISH_TYPOLOGY.items()) / len(ENGLISH_TYPOLOGY)
    total = sum(ENGLISH_WEIGHTS[k] * comp[k] for k in ENGLISH_WEIGHTS)
    return total, comp


def word_distance(a: str, b: str) -> float:
    """Normalized edit distance over percepts (substitution = percept distance / 6, capped at 1; tone ignored)."""
    x = [s for s in P.from_ipa(a) if s.kind != "T"]
    y = [s for s in P.from_ipa(b) if s.kind != "T"]
    if not x or not y:
        return 1.0
    dp = [[0.0] * (len(y) + 1) for _ in range(len(x) + 1)]
    for i in range(len(x) + 1):
        dp[i][0] = i
    for j in range(len(y) + 1):
        dp[0][j] = j
    for i in range(1, len(x) + 1):
        for j in range(1, len(y) + 1):
            sub = min(1.0, P.distance(replace(x[i - 1], tone=0), replace(y[j - 1], tone=0)) / 6)
            dp[i][j] = min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + sub)
    return dp[-1][-1] / max(len(x), len(y))


