def _bare(ipa: str) -> str:
    """IPA without tone letters, length and stress marks, for comparing forms by ear."""
    return re.sub(r"[˥˦˧˨˩ːˑˈˌ\u0300-\u036f]", "", ipa)


def audibly_shares(root: str, word: str) -> bool:
    """Does `word` contain the root word's form (tones and length aside), or for a long root its first or last two
    sounds? A semantic shift or old derivation whose form has drifted away from the root's is not felt."""
    a, b = _bare(root), _bare(word)
    if not a:
        return True
    if len(a) <= 2:   # (a two-sound root heard only at a word's edge: 'ma' inside any word is chance)
        return b.startswith(a) or b.endswith(a)
    return a in b or a[:3] in b or a[-3:] in b


def felt_members(doc: Doc, lex: dict, rid: str, members: list) -> list:
    """The words of a felt root family a speaker can still hear it in (all of them when the root's own word is gone)."""
    anchor = lex.get(((doc.d.get("roots") or {}).get(rid) or {}).get("concept") or "")
    if not anchor or rid not in (anchor.get("roots") or ()):
        # (the root's own word is gone: a member is felt only if it shares three sounds, or two at the start, with
        # another member)
        def near(a: str, b: str) -> bool:
            a, b = _bare(a), _bare(b)
            return a[:2] == b[:2] and len(a) >= 2 or any(a[i:i + 3] in b for i in range(max(0, len(a) - 2)))
        keep = [c for c in members if any(near(lex[c]["ipa"], lex[o]["ipa"]) for o in members if o != c)]
        return keep if len(keep) >= 2 else []
    return [c for c in members if audibly_shares(anchor["ipa"], lex[c]["ipa"])]


def _root_family(doc: Doc, l: dict, lex: dict, field: str = "roots", head: tuple = FELT) -> list[str]:
    """The family of the root with most living words in this lect (per-word `roots` or `etym_roots`, main first; the
    document-level `roots` table)."""
    roots = doc.d.get("roots") or {}
    count: Counter = Counter()
    by: dict = {}
    for c, e in lex.items():
        for r in (e.get(field) or [])[:1]:
            by.setdefault(r, []).append(c)
    for r, cs in by.items():
        count[r] = len(felt_members(doc, lex, r, cs) if field == "roots" else cs)
    cands = [(n, r) for r, n in count.items()]
    fam_n = sum(1 for n, _r in cands if n >= 3)
    share = sum(n for n, _r in cands if n >= 2) / max(1, len(lex))
    out = [head[0], "", head[1] + f" {fam_n} families of 3+ words; {share:.0%} of the {len(lex)} words share a root "
                                  "with another word.", ""]
    if not cands:
        return out + ["No word records a root.", ""]
    n, rid = max(cands, key=lambda x: (x[0], x[1]))
    if n < 2:
        return out + ["Every root here has a single word.", ""]
    members = sorted((c for c, e in lex.items() if rid in (e.get(field) or [])),
                     key=lambda c: (((lex[c].get(field) or []).index(rid)), c))
    if field == "roots":
        members = felt_members(doc, lex, rid, members)
    r = roots.get(rid) or _root_from_id(rid)
    out.append(f"The largest: **{r.get('gloss') or cname(r.get('concept', '?'))}** *{r.get('ipa') or '?'}* "
               f"({r.get('pos', '?')}, coined {kyr(r.get('kyr'))} in {doc.label(r.get('lect'), True)}); {n} words have it "
               f"as their main root, {len(members)} contain it.")
    out += ["", "| meaning | IPA | spelling | roots (main first) | how it was built |", "| --- | --- | --- | --- | --- |"]
    for c in members[:14]:
        e = lex[c]
        others = ", ".join((roots.get(x) or {}).get("gloss") or x.split(":", 1)[-1].split("@")[0].lower()
                           for x in e.get(field) or [])
        out.append(f"| {cname(c)} | {e['ipa']} | {e['roman']} | {others} | {etym_short(doc, e, l['id'], 3)} |")
    if len(members) > 14:
        out.append(f"| … | | | | {len(members) - 14} more |")
    out.append("")
    return out


def _root_from_id(rid: str) -> dict:
    """A root the document table lacks: what its id says (lect:CONCEPT@n)."""
    lect, _, rest = str(rid).partition(":")
    c = rest.split("@", 1)[0]
    return {"lect": lect, "concept": c, "gloss": cname(c), "ipa": None, "kyr": None, "pos": "?"}


def word_family(doc: Doc, l: dict) -> list[str]:
    """Words built on one root (the output's root families), else on one base, inferred from the compound and derivation
    steps in the etymologies (a word belongs to concept X's family when one of its steps compounds or derives from X)."""
    lex = l.get("lexicon") or {}
    if doc.d.get("roots") and any("roots" in e for e in lex.values()):
        out = _root_family(doc, l, lex, "roots", FELT)
        if any("etym_roots" in e for e in lex.values()):
            out += _root_family(doc, l, lex, "etym_roots", HISTORIAN)
        else:
            out += [HISTORIAN[0], "", "This run's file stores no `etym_roots` (it predates them), so only the speaker's "
                    "view is shown.", ""]
        return out
    groups: dict[str, list[str]] = defaultdict(list)
    how = "found through the compounds and derivations in the etymologies"
    for c, e in lex.items():
        for n in doc.chain(e.get("etym")):
            pr = n[3]
            bases = []
            if pr.startswith("compound:"):
                bases = pr.split(":", 1)[1].split("+")
            elif pr.startswith("derive:") and len(n) > 6 and n[6]:
                bases = [n[6].split(" + ")[0]]
            for b in bases:
                if b and b != c and c not in groups[b]:
                    groups[b].append(c)
    if not groups:
        return []
    base, members = max(groups.items(), key=lambda kv: (len(kv[1]), kv[0]))
    if len(members) < 2:
        return []
    out = ["### A word family", ""]
    be = lex.get(base)
    head = f"**{cname(base)}**" + (f" {be['ipa']} ‹{be['roman']}›" if be else "")
    out.append(f"Words built on {head} ({how}):")
    out += ["", "| meaning | IPA | spelling | how |", "| --- | --- | --- | --- |"]
    for c in sorted(members)[:12]:
        e = lex[c]
        out.append(f"| {cname(c)} | {e['ipa']} | {e['roman']} | {_family_how(doc, e, base)} |")
    out.append("")
    return out


