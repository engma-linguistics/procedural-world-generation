class Doc:
    def __init__(self, data: dict):
        self.d = data
        self.lects = {l["id"]: l for l in data["lects"]}
        self.living = [l for l in data["lects"] if l.get("end") is None and l.get("deme") is not None]
        self.nodes = data.get("etym_nodes", [])
        self.rules = data.get("rules", {})
        self.names = data.get("names", {})
        self._roots: dict[int, int] = {}
        self.intel = {}
        for a, b, v in (data.get("intelligibility") or {}).get("now", []):
            self.intel[(a, b)] = self.intel[(b, a)] = v
        self.languages = {}
        for lang in (data.get("families") or {}).get("languages", []):
            for lid in lang["lects"]:
                self.languages[lid] = lang
        self.scholars = {}
        for pid, ent in (self.names.get("scholars") or {}).items():
            for lid in ent.get("lects", []):
                self.scholars[lid] = ent
        self.paths = _gram_paths()
        for l in self.lects.values():
            self._bookify(l)

    @staticmethod
    def _bookify(l: dict) -> None:
        """Spelling columns show the book spelling (romanize book=True from the IPA, the lect's contrasts and inventory); the
        stored full spelling moves to `roman_full` (the Orthography section keeps full spellings)."""
        try:
            o = orth_of(l)
        except Exception:  # noqa: BLE001
            return

        def book(ipa):
            try:
                return o.word(R.from_ipa(ipa), book=True)
            except Exception:  # noqa: BLE001 (a sketch must not die on one odd form)
                return None
        for e in (l.get("lexicon") or {}).values():
            if "roman_full" not in e and e.get("ipa") and (b := book(e["ipa"])):
                e["roman_full"], e["roman"] = e.get("roman"), b
        for g in l.get("grams") or []:
            if "roman_full" not in g and g.get("form_ipa") and (b := book(g["form_ipa"])):
                g["roman_full"], g["form_roman"] = g.get("form_roman"), b

    # etymology
    def chain(self, idx) -> list:
        out = []
        seen = set()
        while isinstance(idx, int) and 0 <= idx < len(self.nodes) and idx not in seen:
            seen.add(idx)
            n = self.nodes[idx]
            out.append(n)
            idx = n[0]
        return out[::-1]

    def root(self, idx) -> int | None:
        if not isinstance(idx, int) or idx < 0:
            return None
        if idx in self._roots:
            return self._roots[idx]
        path = []
        cur = idx
        while cur is not None and cur >= 0 and cur not in self._roots:
            path.append(cur)
            p = self.nodes[cur][0]
            cur = p if isinstance(p, int) and p >= 0 else None
        r = self._roots[cur] if cur is not None and cur in self._roots else (path[-1] if path else idx)
        for x in path:
            self._roots[x] = r
        return r

    def line(self, lid: str) -> list[dict]:
        out, seen = [], set()
        while lid and lid in self.lects and lid not in seen:
            seen.add(lid)
            out.append(self.lects[lid])
            lid = self.lects[lid].get("parent")
        return out  # newest first

    def label(self, lid: str | None, short: bool = False) -> str:
        if not lid:
            return "?"
        l = self.lects.get(lid)
        if l is None:
            return lid
        if l.get("deme") is None:
            sch = (self.names.get("scholars") or {}).get(lid)
            if sch:
                return "Proto-" + sch["roman"]
            return f"the {people(l['people'])} proto-language"
        dn = l.get("deme_name") or f"{people(l['people'])} {l['deme']}"
        if short:
            return dn.split(" (")[0]
        nm = self.deme_name(l)
        dn = dn.replace(" (", ", ").rstrip(")") if "(" in dn else dn
        return f"{nm['roman']} ({dn})" if nm else dn

    def deme_name(self, l: dict) -> dict | None:
        ent = (self.names.get("demes") or {}).get(str(l.get("deme")))
        if ent and ent.get("name") and ent["name"].get("lect") in (l["id"], None):
            return ent["name"]
        if ent and ent.get("name"):
            return ent["name"]
        return None


def cname(c: str) -> str:
    """A concept as a reader sees it: WATER -> water, crop:foxtail_millet -> foxtail millet (crop)."""
    if ":" in c:
        kind, rest = c.split(":", 1)
        return f"{rest.replace('_', ' ')} ({kind})"
    return "I" if c == "I" else c.lower()


def people(p: str) -> str:
    return p.replace("_", " ")


def _gram_paths() -> dict[str, str]:
    """Path id -> 'SOURCE > TARGET (frequency; example)': G ids from the data table, X ids parsed from grammar.py's text
    (read, never imported: another builder may be editing it)."""
    out = {}
    tsv = DATA / "grammaticalization_paths.tsv"
    if tsv.exists():
        head = None
        for line in tsv.read_text(encoding="utf-8").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            cols = line.split("\t")
            if head is None:
                head = cols
                continue
            r = dict(zip(head, cols))
            ex = r.get("example", "")
            out[r["id"]] = f"{r['source_concept']} > {r['target_function'].lower()} ({r.get('frequency_class', '')}" + \
                (f"; e.g. {ex}" if ex else "") + ")"
    src = ROOT / "planet" / "language" / "grammar.py"
    if src.exists():
        for m in re.finditer(r'\("(X\d+)",\s*\(([^)]*)\),\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\)', src.read_text(encoding="utf-8")):
            out.setdefault(m.group(1), f"{m.group(5)} ({m.group(4)})")
    return out


