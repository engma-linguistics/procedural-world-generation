# ---- selection -------------------------------------------------------------------------------------------------------------

def _nonhuman(l):
    return sum(1 for s in inv_segments(l) if P.is_nonhuman(s))


def _clicks(l):
    return sum(1 for s in inv_segments(l) if s.kind == "C" and s.manner == 8)


def _ejectives(l):
    return sum(1 for s in inv_segments(l) if s.kind == "C" and s.larynx == 2)


def _ncv(l):
    inv = l.get("inventory") or {}
    return len(inv.get("consonants", [])), len(inv.get("vowels", []))


CRITERIA = [
    # key, heading, eligibility, score (higher wins), why-text; picked in this order
    ("clicks", "the largest click (or ejective) inventory",
     lambda l: _clicks(l) > 0 or _ejectives(l) >= 2,
     lambda l: (_clicks(l) > 0, sum(_ncv(l))),
     lambda l: f"{_ncv(l)[0]} consonants, {_clicks(l)} of them clicks and {_ejectives(l)} ejectives; {_ncv(l)[1]} vowels"),
    ("tonal_bird", "a tonal kenku or aarakocra language",
     lambda l: l["people"] in ("kenku", "aarakocra") and len((l.get("inventory") or {}).get("tones", [])) >= 3,
     lambda l: (len(l["inventory"]["tones"]), _nonhuman(l), sum(_ncv(l))),
     lambda l: f"{len(l['inventory']['tones'])} tones, {_nonhuman(l)} sounds outside the human voice, "
               f"{_ncv(l)[0]} consonants and {_ncv(l)[1]} vowels"),
    ("dragon", "a dragon language with the most non-human sounds",
     lambda l: l["people"].endswith("dragon") and _nonhuman(l) > 0,
     lambda l: (_nonhuman(l), sum(_ncv(l))),
     lambda l: f"{_nonhuman(l)} of its {sum(_ncv(l))} sounds are outside the human voice"),
    ("tiny", "a tiny inventory with long words",
     lambda l: True,
     lambda l: (-(sum(_ncv(l)) - 3 * (l.get("stats") or {}).get("core_mean_syllables", 0)),),
     lambda l: f"{_ncv(l)[0]} consonants and {_ncv(l)[1]} vowels; core words average "
               f"{(l.get('stats') or {}).get('core_mean_syllables', 0):.2f} syllables"),
    ("conservative", "the most conservative language of a long-lived people",
     lambda l: l.get("gen_yr", 0) >= LONG_LIVED_GEN_YR,
     lambda l: ((l.get("stats") or {}).get("inherited_core_share", 0),
                -(l.get("rules_applied", 0) / max(0.5, l.get("born_kyr", 0) - 0))),
     lambda l: f"generation {l.get('gen_yr', 0):g} years; {(l.get('stats') or {}).get('inherited_core_share', 0):.0%} of "
               f"its core list inherited from the proto-language; {l.get('rules_applied', 0)} sound changes"),
]
LONG_LIVED_GEN_YR = 80.0  # years per generation: elves, drow and dragons in a24559 (humans ~25-30)


def group(p: str) -> str:
    """Kin peoples counted as one for variety: the dragon kinds, the elves (elf, drow, sea elf)."""
    if p.endswith("dragon"):
        return "dragon"
    return "elf" if p in ("elf", "drow", "sea_elf") else p


def pick(doc: Doc) -> list[tuple[str, str, dict, str]]:
    """Criteria in CRITERIA order; each pick must differ in people and true family from the earlier ones, and in people
    group (all dragons one group, all elves one) except for the conservative pick, which only long-lived peoples (elves
    and dragons in practice) can fill."""
    chosen: list[tuple[str, str, dict, str]] = []
    for key, head, ok, score, why in CRITERIA:
        used_p = {c[2]["people"] for c in chosen}
        used_f = {c[2]["family_true"] for c in chosen}
        used_g = set() if key == "conservative" else {group(c[2]["people"]) for c in chosen}
        cands = [l for l in doc.living if ok(l) and l["people"] not in used_p and l["family_true"] not in used_f
                 and group(l["people"]) not in used_g]
        if not cands:
            continue
        best = max(cands, key=lambda l: (score(l), l["id"]))
        chosen.append((key, head, best, why(best)))
    return chosen


def english_ranking(doc: Doc) -> list[tuple[float, dict, dict]]:
    out = [(s, l, c) for l in doc.living for s, c in [english_score(l)]]
    return sorted(out, key=lambda x: (-x[0], x[1]["id"]))


