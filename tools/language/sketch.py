def infobox(doc: Doc, l: dict) -> list[str]:
    pe = (doc.names.get("peoples") or {}).get(l["people"], {})
    nm = doc.deme_name(l)
    rows = []
    if nm:
        rows.append(("Name", f"**{nm['roman']}** ({nm.get('roman_full', nm['roman'])}) /{nm['ipa']}/, "
                             f"'{nm.get('gloss', '')}': the speakers' own name for themselves"))
    gl = pe.get("glossonym")
    if gl and gl.get("lect") == l["id"]:
        rows.append(("Native name of the language", f"**{gl['roman']}** /{gl['ipa']}/, '{gl.get('gloss', '')}'"))
    en = pe.get("endonym")
    if en and en.get("lect") != l["id"]:
        rows.append(("The people's best-known name", f"{en['roman']} /{en['ipa']}/ '{en.get('gloss', '')}' "
                                                    f"(in {doc.label(en.get('lect'), True)})"))
    com = doc.names.get("common") or {}
    ex = (com.get("exonyms") or {}).get(l["people"])
    if ex and com.get("lect") != l["id"]:
        rows.append(("Called in the Common", f"{ex['roman']} /{ex['ipa']}/, '{ex.get('gloss', '')}'"))
    dn = l.get("deme_name") or ""
    region = dn[dn.find("(") + 1:dn.rfind(")")] if "(" in dn else "?"
    rows.append(("Speakers", f"{people(l['people'])} of deme {l['deme']}, {region}; about "
                             f"{int(l.get('population') or 0):,} people; adult second-language share "
                             f"{(l.get('l2') or 0):.0%}; generation {l.get('gen_yr', 0):g} years"))
    lang = doc.languages.get(l["id"])
    if lang:
        others = [x for x in lang["lects"] if x != l["id"]]
        rows.append(("Language", f"{lang['name']}" + (f"; with {len(others)} other dialect(s): "
                                                      + ", ".join(doc.label(x, True) for x in others[:6]) if others else
                                                      "; no other dialects")))
    line = doc.line(l["id"])
    proto = line[-1]
    mid = len(line) - 2
    rows.append(("Family (true descent)", f"descends from {doc.label(proto['id'])} ({kyr(proto.get('born_kyr'))})"
                 + (f" through {mid} intermediate lect(s)" if mid > 0 else " directly")))
    sch = doc.scholars.get(l["id"])
    fs = l.get("family_scholars")
    same = [x for x in doc.living if x.get("family_scholars") == fs] if fs else []
    if sch:
        rows.append(("Family (as scholars group it)", f"{sch['name']} ('{sch.get('gloss', '')}'), {len(same)} living lects"))
    elif fs:
        trues = Counter(x["family_true"] for x in same)
        pp = Counter(people(x["people"]) for x in same)
        if len(same) <= 1:
            rows.append(("Family (as scholars group it)", "an isolate: the comparative method links it to no other "
                                                         "living lect"))
        else:
            rows.append(("Family (as scholars group it)", f"an unnamed comparative grouping of {len(same)} living lects"
                         + (f" from {len(trues)} true families" if len(trues) > 1 else ", matching true descent")
                         + ": " + ", ".join(f"{k} {v}" for k, v in pp.most_common())))
    st = []
    if l.get("how") == "shift":
        st.append(f"the speakers shifted to this language {kyr(l.get('born_kyr'))}")
    if l.get("minority"):
        st.append("a minority language: its deme has shifted to another language, and it lives on beside it")
    sh = l.get("shares_history") or []
    if sh:
        last = sh[-1][1]
        if last:
            top = max(last, key=last.get)
            st.append(f"another language is spreading in the deme: {doc.label(top, True)} ({last[top]:.0%} of speakers now)")
    rows.append(("Status", "; ".join(st) if st else "spoken by its whole deme; no shift recorded"))
    inv = l.get("inventory") or {}
    rows.append(("Sounds", f"{len(inv.get('consonants', []))} consonants, {len(inv.get('vowels', []))} vowels, "
                           f"{len(inv.get('tones', [])) or 'no'} tones"))
    rows.append(("Word order", (l.get("typology") or {}).get("word_order", "?")))
    out = ["| | |", "| --- | --- |"] + [f"| **{a}** | {b} |" for a, b in rows]
    return out


def history(doc: Doc, l: dict) -> list[str]:
    line = doc.line(l["id"])
    out = ["## History", ""]
    steps = []
    for i, x in enumerate(reversed(line)):
        how = x.get("how")
        if x.get("deme") is None:
            steps.append(f"- **{doc.label(x['id'])}**, {kyr(x.get('born_kyr'))}: the reconstructed ancestor "
                         f"({people(x['people'])}).")
            continue
        verb = {"bud": "split off as its own speech", "proto": "continued the proto-language in place",
                "shift": "formed when the speakers took up another language", "arrival": "arrived with its people"
                }.get(how, how)
        s = f"- **{doc.label(x['id'])}**, {kyr(x.get('born_kyr'))}: {verb}"
        if x.get("people") != l["people"]:
            s += f" (spoken by {people(x['people'])})"
        steps.append(s + ".")
    out += ["The line of descent, oldest first:", ""] + steps + [""]
    proto = line[-1]
    pinv, inv = proto.get("inventory") or {}, l.get("inventory") or {}
    if pinv.get("consonants"):
        out += ["| | consonants | vowels | tones |", "| --- | --- | --- | --- |"]
        for nm, iv in ((doc.label(proto["id"]) + f", {kyr(proto.get('born_kyr'))}", pinv), ("now", inv)):
            out.append(f"| {nm} | {len(iv.get('consonants', []))}: {' '.join(sorted(iv.get('consonants', []), key=_c_order))}"
                       f" | {len(iv.get('vowels', []))}: {' '.join(sorted(iv.get('vowels', []), key=_v_order))} | "
                       f"{len(iv.get('tones', [])) or 'none'} |")
        out.append("")
    # shift and substrate
    for shf in doc.d.get("shifts", []):
        if shf.get("to_lect") == l["id"] or shf.get("from_lect") == l["id"]:
            tr = shf.get("trigger") or {}
            if shf.get("to_lect") == l["id"]:
                out.append(f"**Shift.** {kyr(shf.get('kyr'))} the {people(shf.get('speakers', l['people']))} speakers of deme "
                           f"{shf.get('deme')} took up the language of the {people(shf.get('ruler_people', '?'))} "
                           f"({doc.label(shf.get('ruler_lect'), True)}). Trigger: {tr.get('source', tr.get('kind', '?'))}.")
                sw = shf.get("substrate_words") or []
                if sw:
                    out.append(f"From the old language ({doc.label(shf.get('from_lect'), True)}) {len(sw)} words were kept, "
                               f"mostly landscape, plants and animals: {', '.join(cname(w) for w in sw[:14])}"
                               f"{', …' if len(sw) > 14 else ''}.")
                ac = shf.get("accent") or []
                if ac:
                    out.append("The accent the speakers brought (new sound heard as old): "
                               + ", ".join(f"{a} > {b}" for a, b in ac) + ".")
                cq = shf.get("calques") or []
                if cq:
                    out.append("Grammar carried over: " + "; ".join(f"{c['feature'].replace('_', ' ')} {c['from']} > "
                                                                   f"{c['to']}" for c in cq) + ".")
            else:
                out.append(f"**Shift away.** {kyr(shf.get('kyr'))} most of this deme took up "
                           f"{doc.label(shf.get('to_lect'), True)}; this language lives on beside it.")
            out.append("")
    # contacts: adopted changes and loans
    adopted = Counter()
    for x in line:
        for ch in x.get("changes", []):
            if len(ch) > 3 and ch[3]:
                adopted[ch[3]] += 1
    loans = Counter()
    for c, e in (l.get("lexicon") or {}).items():
        for n in doc.chain(e.get("etym")):
            if n[3].startswith("borrow:"):
                loans[n[3].split(":", 1)[1]] += 1
    if adopted or loans:
        s = "**Contact.** "
        if adopted:
            s += ("Sound changes taken up from neighbours by the wave along the line: "
                  + ", ".join(f"{doc.label(k, True)} ({v})" for k, v in adopted.most_common(6)) + ". ")
        if loans:
            s += ("Loan events in the present vocabulary (by donor): "
                  + ", ".join(f"{doc.label(k, True)} ({v})" for k, v in loans.most_common(6)) + ".")
        out += [s, ""]
    # sound changes by stage
    out += ["### Sound changes", ""]
    out.append("Each stage of the line, oldest first; within a stage, by half-millennium. \"Rare sounds merged\" (the "
               "inventory clean-up) is counted, not listed. Ids in the last column are the engine's rule ids.")
    out.append("")
    stages = list(reversed(line))
    for i, x in enumerate(stages):
        chs = x.get("changes") or []
        if i + 1 < len(stages):
            cut = stages[i + 1].get("born_kyr", 0)
            chs = [c for c in chs if c[0] > cut]
        if not chs:
            continue
        causes = Counter(c[2] for c in chs)
        merges = [c for c in chs if c[1] == "simplification"]
        byk = defaultdict(list)
        for c in chs:
            if c[1] != "simplification":
                byk[c[0]].append(c)
        out.append(f"**{doc.label(x['id'])}** ({len(chs)} changes; by cause "
                   + ", ".join(f"{k} {v}" for k, v in causes.most_common()) + f"; {len(merges)} merger rounds)")
        out.append("")
        out += ["| when | changes | rules |", "| --- | --- | --- |"]
        for k in sorted(byk, reverse=True):
            texts, ids = [], []
            for c in byk[k]:
                t = rule_text(doc, c[1])
                if len(c) > 3 and c[3]:
                    t += f" (from {doc.label(c[3], True)})"
                texts.append(t)
                ids.append(c[1])
            out.append(f"| {k:g} kyr | " + "; ".join(texts) + " | <sub>" + " ".join(ids) + "</sub> |")
        out.append("")
    return out


def _allo_text(v) -> str:
    """An allophone entry in words, whatever shape the (future) field takes: str, list, or dict."""
    if isinstance(v, str):
        return v
    if isinstance(v, dict):
        return "; ".join(f"{k}: {_allo_text(x)}" for k, x in v.items())
    if isinstance(v, (list, tuple)):
        return "; ".join(_allo_text(x) for x in v)
    return str(v)


def phonology(doc: Doc, l: dict) -> list[str]:
    inv = l.get("inventory") or {}
    cons, vows, tones = inv.get("consonants", []), inv.get("vowels", []), inv.get("tones", [])
    out = ["## Phonology", "", "### Consonants", ""]
    out.append(consonant_chart(cons))
    out.append("")
    out.append("Where symbols share a cell, the voiceless ones come first and the voiced follow the dot. Secondary "
               "articulation (ʷ ʲ ˠ ˤ) and length (ː) stay in the cell of the plain sound.")
    out += ["", "### Vowels", "", vowel_chart(vows), ""]
    vsegs = [(v, seg(v)) for v in vows]
    longs = [v for v, s in vsegs if s and s.length]
    nas = [v for v, s in vsegs if s and s.nasal]
    phon = [v for v, s in vsegs if s and s.phonation]
    notes = ["Unrounded vowels come before the dot, rounded after it."]
    notes.append(f"Length: {'long vowels ' + ' '.join(longs) if longs else 'no long vowels'}.")
    notes.append(f"Nasality: {'nasal vowels ' + ' '.join(nas) if nas else 'no nasal vowels'}.")
    if phon:
        notes.append("Phonation: " + " ".join(phon) + ".")
    out += [" ".join(notes), ""]
    nh = nonhuman_footnotes(cons + vows)
    if nh:
        out += ["**Sounds outside the human voice** (house and VoQS symbols, `planet/language/data/symbols.tsv`):", ""]
        out += [f"- {x}" for x in nh] + [""]
    out += ["### Tone, syllables and stress", ""]
    if tones:
        out += ["| tone | IPA | spelling |", "| --- | --- | --- |"]
        out += [f"| {TONES[t][0]} | a{TONES[t][1]} | {TONES[t][2]} |" for t in tones if t in TONES]
        out += ["", f"The language has {len(tones)} phonemic tones, marked on every vowel in the IPA here."]
    else:
        out.append("No phonemic tone.")
    shapes = inv.get("shapes") or {}
    if shapes:
        sh = ", ".join(f"{k} {v:.0%}" for k, v in sorted(shapes.items(), key=lambda kv: -kv[1]))
        out.append(f"Syllable shapes (share of syllables in the word-shape model): {sh}. At most "
                   f"{inv.get('max_onset', '?')} consonant(s) before the vowel and {inv.get('max_coda', '?')} after it.")
    stress = inv.get("stress")
    out.append({"none": "Stress is not phonemic (no fixed stress).", "penult": "Stress falls on the next-to-last syllable.",
                "initial": "Stress falls on the first syllable.", "final": "Stress falls on the last syllable."
                }.get(stress, f"Stress: {stress}."))
    stt = l.get("stats") or {}
    if stt:
        out.append(f"Core words average {stt.get('core_mean_syllables', 0):.2f} syllables "
                   f"({stt.get('core_mean_segments', 0):.1f} sounds); {stt.get('homophone_share', 0):.0%} of words share "
                   f"their form with another word.")
    out.append("")
    allo = inv.get("allophones") or l.get("allophones")
    out += ["### Allophony", ""]
    if allo and isinstance(allo, list) and all(isinstance(a, dict) and "ipa" in a for a in allo):
        out += ["| allophone | phoneme | where |", "| --- | --- | --- |"]
        for a in allo:
            where = re.sub(r"\s*\([^)]*\)\s*$", "", str(a.get("where") or a.get("test") or "")).strip()
            out.append(f"| [{a['ipa']}] | /{a.get('of', '?')}/ | {where} |")
    elif allo:
        if isinstance(allo, dict):
            out += ["| phoneme | realisations |", "| --- | --- |"]
            for k, v in allo.items():
                out.append(f"| {k} | {_allo_text(v)} |")
        else:
            for a in allo:
                out.append(f"- {_allo_text(a)}")
    else:
        out.append("This output records no allophones (the engine stores sounds as phonemes only).")
    out.append("")
    return out


def _c_order(sym: str) -> tuple:
    s = seg(sym)
    if s is None:
        return (99, 99, sym)
    pc = place_col(s)
    return (_row_key(manner_row(s)), PLACE_COLS.index(pc) if pc in PLACE_COLS else 99, s.voice, sym)


def _v_order(sym: str) -> tuple:
    s = seg(sym)
    return (99, 0, sym) if s is None else (-s.height, s.back, s.round, s.length, s.nasal, sym)


def orthography(l: dict) -> list[str]:
    inv = l.get("inventory") or {}
    o = orth_of(l)
    cs = o.cs
    out = ["## Orthography", "",
           "The house romanization in two registers: the full spelling (workbench, one letter or digraph per sound, "
           "tone marks) and the book spelling (lossy: no tone, plain vowels, and at most "
           f"{R.BOOK_DIACRITIC_BUDGET} diacritic letters kept for the whole language; one spelling per sound in every word). "
           "Allophones are spelled as their phonemes.", ""]
    for title, syms in (("Consonants", sorted(inv.get("consonants", []), key=_c_order)),
                        ("Vowels", sorted(inv.get("vowels", []), key=_v_order))):
        rows = []
        for sym in syms:
            s = seg(sym)
            if s is None:
                continue
            try:
                full, book = R.spell(s, cs), R._apply_folds(R.spell(s, cs, book=True), o.folds)
            except Exception:  # noqa: BLE001
                full = book = "?"
            rows.append(f"{sym} ‹{full}›" + (f" ‹{book}›" if book != full else ""))
        out.append(f"**{title}:** " + " · ".join(rows))
        out.append("")
    if inv.get("tones"):
        out.append("Tones are written over the vowel: " + ", ".join(f"{TONES[t][0]} {TONES[t][2]}" for t in inv["tones"]
                                                                    if t in TONES) + " (Yoruba-style).")
        out.append("")
    out.append("Where two spellings are given the second is the book spelling.")
    if o.lossy:
        out.append(" Book folds that merge two sounds: " + ", ".join(f"‹{g}› is written ‹{a}›" for g, a in o.lossy) + ".")
    out.append("")
    return out


CASE_FNS = {"ACC", "ERG", "DAT", "GEN", "LOC", "ABL", "ALL", "INS", "COM"}


def _typology_clashes(t: dict, grams: list[dict]) -> list[str]:
    fns = {g["function"] for g in grams if g.get("form_ipa")}
    # (WALS 49 counts inflectional case: a free case-function marker is an adposition, case from clitic level on)
    case_fns = {g["function"] for g in grams if g.get("form_ipa") and (g.get("level") or 0) >= 1}
    out = []
    for feat, val, test, what in (
            ("number", "none", {"PL", "DU"}, "plural or dual marker"),
            ("definite_article", "none", {"DEF"}, "definite marker"),
            ("indefinite_article", "none", {"INDEF"}, "indefinite marker"),
            ("case", "none", CASE_FNS & case_fns, "case marker"),
            ("evidentiality", "none", {"EVID.REP", "EVID.DIR"}, "evidential marker"),
            ("past", "none", {"PAST", "RECPST"}, "past marker"),
            ("future", "none", {"FUT"}, "future marker"),
            ("progressive", "none", {"PROG"}, "progressive marker"),
            ("habitual", "none", {"HAB"}, "habitual marker")):
        hit = sorted(fns & test)
        if t.get(feat) == val and hit:
            art = "an" if what[0] in "aeiou" else "a"
            out.append(f"{feat.replace('_', ' ')} is 'none' but {art} {what} is live ({', '.join(hit)})")
    return out


def grammar(doc: Doc, l: dict) -> list[str]:
    t = l.get("typology") or {}
    out = ["## Grammar", ""]
    out += typology_prose(t)
    clash = _typology_clashes(t, l.get("grams") or [])
    if clash:
        out.append("Note on the data: the typology features and the live markers disagree here (" + "; ".join(clash)
                   + "). Both are shown as recorded.")
    cx = l.get("complexity") or {}
    if cx:
        out.append(f"Measured morphology: {cx.get('live_grams', 0)} live grammatical markers, mean bondedness "
                   f"{cx.get('mean_level', 0):.1f} (0 free word … 3 fused), {cx.get('cells', 0)} paradigm cells, "
                   f"{cx.get('allomorphy', 0)} of them with allomorphy.")
    out.append("")
    grams = l.get("grams") or []
    out += ["### Grammatical markers", ""]
    if grams:
        out += ["| function | form | spelling | status | attaches | source | since |",
                "| --- | --- | --- | --- | --- | --- | --- |"]
        for gm in sorted(grams, key=lambda g: (-(g.get("born_kyr") or 0))):
            src = gm.get("source") or []
            sc = f"from '{cname(src[0])}'" if src and src[0] not in (None, "?") else "a coined particle"
            pid = src[1] if len(src) > 1 else ""
            path = doc.paths.get(pid, "")
            pth = f" <sub>{pid}: {path}</sub>" if path else (f" <sub>{pid}</sub>" if pid else "")
            att = f"{'before' if gm.get('side') == 'pre' else 'after'} the {HOST.get(gm.get('host'), gm.get('host'))}"
            out.append(f"| {GLOSS.get(gm['function'], gm['function'])} | {gm.get('form_ipa') or '∅'} | "
                       f"{gm.get('form_roman') or ''} | {gm.get('level_name', gm.get('level'))} | {att} | "
                       f"{sc}{pth} | {kyr(gm.get('born_kyr'))} |")
    else:
        out.append("No grammatical markers are live.")
    out.append("")
    par = l.get("paradigms") or {}
    for key, title in (("nouns", "Noun paradigms"), ("verbs", "Verb paradigms")):
        p = par.get(key) or {}
        cols = p.get("columns") or []
        rows = p.get("rows") or []
        if not rows or cols == ["lemma"]:
            continue
        out += [f"### {title}", "", "| | " + " | ".join(cols) + " |", "| --- |" + " --- |" * len(cols)]
        for r in rows:
            cells = []
            for c in cols:
                ce = (r.get("cells") or {}).get(c)
                if not ce:
                    cells.append("–")
                    continue
                segd = (r.get("segmented") or {}).get(c)
                irr = "†" if c in (r.get("irregular") or []) else ""
                cells.append(f"{segd or ce['ipa']}{irr}<br>‹{ce.get('roman', '')}›")
            out.append(f"| **{r['concept'].lower()}** | " + " | ".join(cells) + " |")
        out += ["", "Hyphens show the morpheme boundary where the engine segments the form; † marks a form the engine "
                    "flags as irregular (the marker or the stem has an alternation).", ""]
    out += pronouns(doc, l)
    out += grammar_sketch(l)
    return out


def ensure_sentences(l: dict) -> None:
    """Files written before round 5 have no `sentences` / `grammar_notes`: build them from the record (the same code the
    pass runs)."""
    if "sentences" not in l or "grammar_notes" not in l:
        SN.enrich(l)


def interlinear(form: str, gloss: str) -> list[str]:
    """One interlinear example as a two-row table: the form line (morpheme breaks) over the gloss line, word by word."""
    fw, gw = form.split(" "), gloss.split(" ")
    if len(fw) != len(gw):
        return [f"*{form}*", "", gloss]
    return ["| " + " | ".join(f"*{x}*" for x in fw) + " |", "|" + " --- |" * len(fw), "| " + " | ".join(gw) + " |"]


def grammar_sketch(l: dict) -> list[str]:
    ensure_sentences(l)
    notes = l.get("grammar_notes") or []
    if not notes:
        return []
    sent_no = {s["id"]: i for i, s in enumerate(l.get("sentences") or [], 1)}
    out = ["### Grammar sketch", "",
           "Built from the typology and the live markers above (planet/language/sentences.py); where the engine tracks no "
           "marker for a construction, the form is the word such markers commonly grow from, and the text says so. "
           "Examples are glossed by the Leipzig rules (abbreviations under Sample sentences).", ""]
    for n in notes:
        out += [f"**{n['topic']}.** {n['text']}", ""]
        for ex in (n.get("ex") or [])[:3]:
            e = SN.example(l, ex)
            if e is None:
                continue
            form, gloss, en, sent = e
            out += interlinear(form, gloss) + ["", f"‘{en}’" + (f" (sentence {sent_no[sent['id']]} below)"
                                                                 if sent and sent["id"] in sent_no else ""), ""]
    return out


def pronouns(doc: Doc, l: dict) -> list[str]:
    lex = l.get("lexicon") or {}
    out = ["### Pronouns", "", "| person | singular | plural |", "| --- | --- | --- |"]
    forms = {}
    rows = list(PRONOUNS)
    if lex.get("WE (INCLUSIVE)"):   # (grammar phase A: a lect with the distinction keeps its old 'we' as the exclusive)
        rows[0:1] = [("1st (exclusive)", "I", "WE"), ("1st + 2nd (inclusive)", None, "WE (INCLUSIVE)")]
    for p, sg, pl in rows:
        cells = []
        for c in (sg, pl):
            e = lex.get(c) if c else None
            if e:
                forms[c] = e["ipa"]
                cells.append(f"{e['ipa']} ‹{e['roman']}›")
            else:
                cells.append("–")
        out.append(f"| {p} | " + " | ".join(cells) + " |")
    he = lex.get("HE")
    notes = []
    if he and he.get("ipa") != forms.get("HE OR SHE OR IT"):
        notes.append(f"A separate word for 'he' is recorded: {he['ipa']} ‹{he['roman']}›.")
    seen = defaultdict(list)
    for c, f in forms.items():
        seen[f].append(f"'{cname(c)}'")
    for f, cs in seen.items():
        if len(cs) > 1:
            notes.append(f"{' and '.join(cs)} are the same word ({f}).")
    if (l.get("typology") or {}).get("clusivity") == "yes" and not lex.get("WE (INCLUSIVE)"):
        notes.append("The typology marks an inclusive/exclusive 'we', but the lexicon holds only one 'we' form.")
    elif lex.get("WE (INCLUSIVE)"):
        notes.append("'We' has two forms: an inclusive one (the hearer is among us) and an exclusive one (not you).")
    if (l.get("typology") or {}).get("pro_drop") == "yes":
        notes.append("Subject pronouns are usually dropped.")
    out += [""] + ([" ".join(notes), ""] if notes else [])
    bound = [g for g in (l.get("grams") or []) if PERSON_RE.match(g["function"])]
    if bound:
        out += ["Person markers among the grammatical markers (agreement, or pronouns on their way to it):", "",
                "| person | form | spelling | status | attaches | from |",
                "| --- | --- | --- | --- | --- | --- |"]
        order = ["1SG", "2SG", "3SG", "1DU", "2DU", "3DU", "1PL", "2PL", "3PL"]
        for g in sorted(bound, key=lambda g: order.index(g["function"]) if g["function"] in order else 99):
            s0 = (g.get("source") or ["?"])[0]
            src = cname(s0) if s0 and s0 != "?" else "a coined form"
            out.append(f"| {g['function']} | {g.get('form_ipa') or '∅'} | {g.get('form_roman', '')} | "
                       f"{g.get('level_name', '')} | {'before' if g.get('side') == 'pre' else 'after'} the "
                       f"{HOST.get(g.get('host'), g.get('host'))} | {src}, {kyr(g.get('born_kyr'))} |")
        out.append("")
    return out


def _family_how(doc: Doc, e: dict, base: str) -> str:
    """The etymology from the step that builds on `base` onwards."""
    full = etym_short(doc, e, "", max_steps=99).split(" → ")
    i = next((k for k, x in enumerate(full) if base.replace("+", " + ") in x or x.startswith(base + " + ")), 0)
    tail = full[i:]
    return " → ".join(tail if len(tail) <= 3 else tail[:2] + ["…", tail[-1]])


