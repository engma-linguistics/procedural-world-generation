def seg(sym: str):
    return P.parse_segment(sym)


def place_col(s) -> str:
    if s.double:
        return "Labial-velar"
    if s.retroflex:
        return "Retroflex"
    if s.place == 0:
        return "Labiodental" if s.labiodental else "Bilabial"
    return {1: "Dental", 2: "Alveolar", 3: "Post-alveolar", 4: "Palatal", 5: "Velar", 6: "Uvular", 7: "Pharyngeal",
            8: "Glottal"}.get(s.place, "Alveolar")


def manner_row(s) -> str:
    m, lat = s.manner, s.lateral
    if m == 0:
        base = {2: "Ejective", 3: "Implosive"}.get(s.larynx, "Plosive")
    elif m == 1:
        base = "Lateral affricate" if lat else "Affricate"
    elif m == 2:
        base = "Lateral fricative" if lat else ("Sibilant fricative" if s.sibilant else "Non-sibilant fricative")
    elif m == 3:
        base = "Nasal"
    elif m == 4:
        base = "Lateral approximant" if lat else "Approximant"
    elif m == 5:
        base = "Lateral approximant"
    elif m == 6:
        base = "Trill"
    elif m == 7:
        base = "Lateral flap" if lat else "Tap or flap"
    elif m == 8:
        base = "Click"
    else:
        base = "Percussive"
    q = []
    if s.prenasal:
        q.append("prenasalized")
    if s.larynx == 1:
        q.append("aspirated")
    if m == 1 and s.larynx == 2:
        q.append("ejective")
    if s.phonation in (1, 2, 3, 4):
        q.append(SERIES[(0, s.phonation)])
    return base + (" (" + ", ".join(q) + ")" if q else "")


def _row_key(name: str) -> tuple:
    base = name.split(" (")[0]
    return (MANNER_ROWS.index(base) if base in MANNER_ROWS else 99, name)


def consonant_chart(symbols: list[str]) -> str:
    cells: dict[tuple, list] = defaultdict(list)
    for sym in symbols:
        s = seg(sym)
        if s is None:
            cells[("Other", "Other")].append((0, 0, sym))
            continue
        cells[(manner_row(s), place_col(s))].append((s.voice, s.secondary * 2 + s.length, sym))
    rows = sorted({r for r, _ in cells}, key=_row_key)
    cols = [c for c in PLACE_COLS + ["Other"] if any(k[1] == c for k in cells)]
    out = ["| | " + " | ".join(cols) + " |", "| --- |" + " --- |" * len(cols)]
    for r in rows:
        line = []
        for c in cols:
            xs = sorted(cells.get((r, c), []))
            vl = [x[2] for x in xs if x[0] == 0]
            vd = [x[2] for x in xs if x[0] == 1]
            line.append(" ".join(vl + ([" "] if vl and vd else []) + vd).replace("   ", " · "))
        out.append(f"| **{r}** | " + " | ".join(line) + " |")
    return "\n".join(out)


def vowel_chart(symbols: list[str]) -> str:
    cells: dict[tuple, list] = defaultdict(list)
    for sym in symbols:
        s = seg(sym)
        if s is None:
            continue
        mods = s.length + 2 * s.nasal + 4 * bool(s.phonation) + 8 * bool(s.source2 or s.register)
        cells[(s.height, s.back)].append((s.round, mods, sym))
    hs = sorted({h for h, _ in cells}, reverse=True)
    bs = sorted({b for _, b in cells})
    out = ["| | " + " | ".join(BACKS[b] for b in bs) + " |", "| --- |" + " --- |" * len(bs)]
    for h in hs:
        line = []
        for b in bs:
            xs = sorted(cells.get((h, b), []))
            un = [x[2] for x in xs if x[0] == 0]
            ro = [x[2] for x in xs if x[0] == 1]
            line.append(" ".join(un + (["·"] if un and ro else []) + ro))
        out.append(f"| **{HEIGHTS[h]}** | " + " | ".join(line) + " |")
    return "\n".join(out)


def symbol_notes() -> dict[str, str]:
    notes = {}
    for sy in P.symbols():
        if sy.source in ("house", "voqs") and sy.note:
            notes[sy.symbol] = sy.note
    return notes


def nonhuman_footnotes(symbols: list[str]) -> list[str]:
    """One line per non-human (house or VoQS) mark used in the inventory, with the symbol table's note."""
    notes = symbol_notes()
    used = []
    for mark, what in NONHUMAN_MARKS.items():
        hits = [s for s in symbols if mark in s]
        if not hits:
            continue
        note = next((notes[k] for k in notes if mark in k), "")
        used.append(f"**{mark}** ({what}): {', '.join(hits)}." + (f" Symbol table: {note}." if note else ""))
    for s in symbols:
        g = seg(s)
        if g is not None and g.kind == "C" and g.manner == 9 and not any(m in s for m in NONHUMAN_MARKS):
            used.append(f"**{s}**: a percussive (a sound made by striking, not by air). {notes.get(s, '')}".strip())
    return used


