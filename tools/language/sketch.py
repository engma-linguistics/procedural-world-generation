LEIPZIG = {"1": "first person", "2": "second person", "3": "third person", "SG": "singular", "PL": "plural", "DU": "dual",
           "DEF": "definite", "INDF": "indefinite", "GEN": "genitive", "LOC": "locative", "ABL": "ablative",
           "ALL": "allative", "DAT": "dative", "ACC": "accusative", "ERG": "ergative", "INS": "instrumental",
           "COM": "comitative", "PST": "past", "FUT": "future", "PRF": "perfect", "PROG": "progressive",
           "IPFV": "imperfective", "HAB": "habitual", "NEG": "negation", "Q": "question particle", "REL": "relativizer",
           "COP": "copula", "CAUS": "causative", "PASS": "passive", "REFL": "reflexive", "DIM": "diminutive",
           "M": "masculine", "F": "feminine", "N": "neuter", **SN.EXTRA_ABBR}


def _abbrs(sents: list) -> list[str]:
    """The gloss abbreviations the sentences use, explained."""
    used = set()
    for s in sents:
        for _f, g in s["w"]:
            for tok in re.split(r"[-=.\s]", g):
                m = re.fullmatch(r"([123])(SG|PL|DU)", tok)
                if m:
                    used.update(m.groups())
                elif tok in LEIPZIG or re.fullmatch(r"CL\d+", tok):
                    used.add(tok)
    out = []
    for k in sorted(used):
        out.append(f"{k} {LEIPZIG[k]}" if k in LEIPZIG else f"{k} noun class {k[2:]}")
    return out


def sample_sentences(l: dict) -> list[str]:
    ensure_sentences(l)
    sents = l.get("sentences") or []
    if not sents:
        return []
    try:
        o = orth_of(l)
    except Exception:  # noqa: BLE001
        o = None

    def book(w):
        try:
            return o.word(R.from_ipa(w), book=True)
        except Exception:  # noqa: BLE001
            return w
    out = ["## Sample sentences", "",
           "Built from this language's own words, word order, markers and agreement (planet/language/sentences.py). Each "
           "has the form line (‘-’ an affix boundary, ‘=’ a clitic boundary), a morpheme-by-morpheme gloss, the free "
           "translation, then the whole sentence in IPA (after the simple joining rules: a glide between two vowels, "
           "a nasal taking the place of a following stop) and in the book spelling. Nothing here is attested speech; it "
           "is what the grammar data implies.", ""]
    for i, s in enumerate(sents, 1):
        form = " ".join(w[0] for w in s["w"])
        gloss = " ".join(w[1] for w in s["w"])
        out += [f"**({i})** ‘{s['en']}’", ""] + interlinear(form, gloss) + [""]
        sp = " ".join(book(w) for w in s["ipa"].split(" "))
        sp = sp[:1].upper() + sp[1:] + ("?" if s.get("q") or s["en"].endswith("?") else ".")
        out += [f"/{s['ipa']}/ · ‹{sp}›" + (" · rising intonation" if s.get("q") else ""), ""]
        if s.get("note"):
            out += [f"<sub>{s['note']}</sub>", ""]
    ab = _abbrs(sents)
    if ab:
        out += ["Abbreviations: " + "; ".join(ab) + ".", ""]
    return out


def core_roots(doc: Doc, l: dict) -> dict[str, int]:
    lex = l.get("lexicon") or {}
    out = {}
    for c in doc.d.get("snapshot_concepts", []):
        e = lex.get(c)
        if e and isinstance(e.get("etym"), int):
            r = doc.root(e["etym"])
            if r is not None:
                out[c] = r
    return out


def split_kyr(doc: Doc, a: str, b: str) -> float | None:
    la, lb = doc.line(a), doc.line(b)
    ids_b = [x["id"] for x in lb]
    for i, x in enumerate(la):
        if x["id"] in ids_b:
            j = ids_b.index(x["id"])
            cands = [la[i - 1].get("born_kyr")] if i > 0 else []
            cands += [lb[j - 1].get("born_kyr")] if j > 0 else []
            cands = [c for c in cands if c is not None]
            return max(cands) if cands else None
    return None


def comparison(doc: Doc, l: dict, roots_cache: dict) -> list[str]:
    mine = roots_cache.setdefault(l["id"], core_roots(doc, l))
    scores = []
    for o in doc.living:
        if o["id"] == l["id"]:
            continue
        theirs = roots_cache.get(o["id"])
        if theirs is None:
            theirs = roots_cache[o["id"]] = core_roots(doc, o)
        both = [c for c in mine if c in theirs]
        if not both:
            continue
        sh = sum(mine[c] == theirs[c] for c in both) / len(both)
        it = doc.intel.get((l["id"], o["id"]))
        if sh > 0 or it:
            scores.append((sh, it or 0.0, o))
    near = sorted(scores, key=lambda s: (-s[0], -s[1]))[:6]
    by_int = sorted([s for s in scores if s[1] > 0], key=lambda s: -s[1])[:3]
    rows = near + [s for s in by_int if s not in near]
    out = ["## Relatives and intelligibility", ""]
    if not rows:
        out += ["No living lect shares a core word root with this one, and none is mutually intelligible with it.", ""]
        return out
    out += ["Shared-origin share: the share of core-100 meanings whose words go back to the same etymon (true cognates, "
            "and loans between the two). Intelligibility is the engine's estimate (blind cognates, how far the cognates "
            "have drifted, and grammar differences).", "",
            "| lect | people | split | shared origin | intelligibility |", "| --- | --- | --- | --- | --- |"]
    for sh, it, o in rows:
        sk = split_kyr(doc, l["id"], o["id"])
        out.append(f"| {doc.label(o['id'])} <sub>{o['id']}</sub> | {people(o['people'])} | "
                   f"{kyr(sk) if sk is not None else 'not related by descent'} | {sh:.0%} | "
                   f"{f'{it:.0%}' if it else '–'} |")
    out.append("")
    return out



def _table_pipes(text: str) -> str:
    """Escape a romanized click spelt '|' inside a markdown table row (Pxeyag|he), which would otherwise split the cell:
    a pipe is a cell border only with a space or the line's edge on both sides."""
    def row(ln: str) -> str:
        if not ln.startswith("|"):
            return ln
        return re.sub(r"(?<!\\)\|", lambda m: m.group(0) if (m.start() == 0 or ln[m.start() - 1].isspace())
                      and (m.end() == len(ln) or ln[m.end()].isspace()) else "\\|", ln)
    return "\n".join(row(ln) for ln in text.split("\n"))


