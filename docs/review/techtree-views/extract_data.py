"""Copies one stored peoples run's technology tree (meta.techtree) and what the mockups need around it into tech-data.js.

Read-only from the store. tech-data.js is plain JSON assigned to a global (window.TT) so the pages work from file://.
    uv run python docs/review/techtree-views/extract_data.py [RUN_DIR]
Maps: the people holding most of each cell (layer peoples, index into meta.lineages; 255 none) and land/sea, at a few
moments, resampled to a 360 x 180 equirectangular raster (nearest cell), one character per pixel.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

STORE = Path("/home/daniel/personal/repos/procedural-world-generation")
RUN = Path(sys.argv[1]) if len(sys.argv) > 1 else STORE / "runs" / "3097e3"
OUT = Path(__file__).parent / "tech-data.js"
W, H = 360, 180
MOMENTS = [2000, 1000, 500, 300, 200, 100, 50, 25, 12, 6, 3, 1, 0]  # kyr ago
ALPHA = "".join(chr(c) for c in range(48, 127) if chr(c) not in "\\\"'`")  # 0 sea, 1 empty land, 2+ people


def layer(run, name, frames):
    m = run["layers"][name]
    a = np.memmap(RUN / m["file"], dtype=m["dtype"], mode="r", shape=tuple(m["shape"]))
    return np.asarray(a[frames])


def main():
    run = json.loads((RUN / "run.json").read_text())
    m = run["meta"]
    tt = m["techtree"]
    grid = json.loads((RUN / run["grid"]).resolve().read_text())
    lat, lon = np.radians(np.asarray(grid["lat"], np.float32)), np.radians(np.asarray(grid["lon"], np.float32))
    cell = np.stack([np.cos(lat) * np.cos(lon), np.cos(lat) * np.sin(lon), np.sin(lat)], 1).astype(np.float32)
    py, px = np.mgrid[0:H, 0:W]
    plat, plon = np.radians(90 - (py + 0.5) * 180 / H), np.radians(-180 + (px + 0.5) * 360 / W)
    pix = np.stack([np.cos(plat) * np.cos(plon), np.cos(plat) * np.sin(plon), np.sin(plat)], -1).reshape(-1, 3).astype(np.float32)
    near = np.concatenate([np.argmax(pix[i:i + 2000] @ cell.T, 1) for i in range(0, len(pix), 2000)])
    ts = np.array([f["t"] for f in run["frames"]])
    frames = [int(np.argmin(np.abs(ts + k))) for k in MOMENTS]
    peo = layer(run, "peoples", frames)
    land = (layer(run, "elevation", frames) > 0) | (layer(run, "ice", frames) > 0)
    lines = m["lineages"]
    maps = []
    for j, k in enumerate(MOMENTS):
        v = np.where(land[j], 1, 0).astype(np.int32)
        p = peo[j].astype(np.int32)
        v = np.where(land[j] & (p != 255), p + 2, v)
        maps.append({"kyr": float(-ts[frames[j]]), "px": "".join(ALPHA[x] for x in v[near])})
    pres = (m.get("present") or {}).get("lines") or {}
    keep = set(tt["known"])
    out = {
        "run": run["id"], "run_name": run["name"], "world": m["world"], "tree": m.get("tree_name"), "era": tt["era"], "mode": tt["mode"],
        "tracks": tt["tracks"], "techs": tt["techs"], "known": tt["known"], "firsts": tt["firsts"], "goods_checked": tt.get("goods_checked"),
        "lines": [{"index": l["index"], "id": l["id"], "name": l["name"].split(" (")[0], "full": l["name"], "origin": l["origin"],
                   "parents": l.get("parents") or [], "group_of": l.get("group_of"), "leaf": bool(l.get("leaf")),
                   "started_kyr": l.get("started_kyr"), "ended_kyr": l.get("ended_kyr"), "color": l.get("color"), "overlay": bool(l.get("overlay")),
                   "in_tree": l["id"] in keep, "centroid": (pres.get(l["id"]) or {}).get("centroid"),
                   "population": (pres.get(l["id"]) or {}).get("population"),
                   "origin_place": [l["origin_place"]["lat"], l["origin_place"]["lon"]] if l.get("origin_place") else None}
                  for l in lines],
        "map": {"w": W, "h": H, "alphabet": ALPHA, "moments": maps},
    }
    OUT.write_text("// generated by extract_data.py from run " + run["id"] + " (world " + m["world"] + "); do not edit\nwindow.TT = "
                   + json.dumps(out, separators=(",", ":")) + ";\n")
    print(OUT, OUT.stat().st_size // 1024, "KiB")


if __name__ == "__main__":
    main()
